import { readFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';

import { diskDifferences, selectedDisk } from '../confirmation/compare-safety.mjs';
import { normalizeStorage } from '../discovery/normalize-facts.mjs';
import { isRecord, reason } from '../discovery/validate-facts.mjs';
import { parsePlanText, validatePlan } from '../plan/validate-plan.mjs';

// Operation kinds the engine does not implement yet; a plan that contains one is rejected before any
// destructive step, never partially applied.
export const UNIMPLEMENTED_KINDS = [
  'install_limine_snapshot_tools',
  'sync_limine_snapshot_entries',
];

const NEXT_STEP_REGENERATE = 'Generate a new plan with this artifact, review it, and confirm it again.';

// A result is a NUL-delimited stream: the first field is "ok" or "fail". It carries no JSON, so the Bash
// orchestrator reads it with `read -r -d ''` and needs no JSON parser.
function stream(fields) {
  return fields.map(field => `${String(field)}\0`).join('');
}

function failure(outcome, item, operation = '') {
  return stream(['fail', outcome, item.code, item.message, item.next_step, operation]);
}

// Flattens a parameter value into key/value pairs: scalars as text, lists of scalars joined by newlines, and
// objects by dotted keys.
function flatten(key, value, pairs) {
  if (Array.isArray(value)) {
    if (value.every(item => !isRecord(item) && !Array.isArray(item))) {
      pairs.push([key, value.map(String).join('\n')]);
    } else {
      value.forEach((item, index) => flatten(`${key}.${index}`, item, pairs));
    }
  } else if (isRecord(value)) {
    for (const [name, inner] of Object.entries(value)) flatten(`${key}.${name}`, inner, pairs);
  } else {
    pairs.push([key, String(value)]);
  }
}

function hasUnsafeText(text) {
  return text.includes('\0');
}

function readOption(args, name) {
  const index = args.indexOf(name);
  return index === -1 ? undefined : args[index + 1];
}

export function verifyPlan(text, { digest, commit, dirty }) {
  const parsed = parsePlanText(text);
  if (parsed.plan === undefined) return failure('blocked', parsed.reasons[0]);
  const { plan } = parsed;

  const binding = plan.facts_binding;
  if (isRecord(binding) && (binding.commit !== commit || binding.dirty !== (dirty === 'true'))) {
    return failure('blocked', reason(
      'engine_version_mismatch',
      'The plan was generated by a different code identity than the running installation artifact.',
      NEXT_STEP_REGENERATE,
    ));
  }

  const problems = validatePlan(plan);
  if (problems.length > 0) {
    const mismatch = problems.find(item => item.code === 'digest_mismatch');
    return failure(mismatch === undefined ? 'blocked' : 'invalidated', mismatch ?? problems[0]);
  }
  if (plan.digest.value !== digest) {
    return failure('invalidated', reason(
      'digest_mismatch',
      'The plan digest differs from the digest that was confirmed.',
      NEXT_STEP_REGENERATE,
    ));
  }
  const unimplemented = plan.operations.find(operation => UNIMPLEMENTED_KINDS.includes(operation.kind));
  if (unimplemented !== undefined) {
    return failure('blocked', reason(
      'stage_failed',
      `The installation engine does not implement the operation ${unimplemented.kind} yet.`,
      'Select a storage option this version of the engine implements, then generate and confirm a new plan.',
    ), unimplemented.kind);
  }

  const disk = plan.target.disk;
  const fields = [
    'ok',
    plan.digest.value,
    plan.choices.storage_option.value,
    plan.choices.hibernation.value,
    disk.path ?? '',
    disk.by_id ?? '',
    plan.operations.length,
  ];
  for (const operation of plan.operations) {
    const pairs = [];
    for (const [key, value] of Object.entries(operation.parameters)) flatten(key, value, pairs);
    fields.push('op', operation.id, operation.description, pairs.length);
    for (const [key, value] of pairs) fields.push(key, value);
  }
  if (fields.some(field => hasUnsafeText(String(field)))) {
    return failure('blocked', reason('plan_invalid_type', 'The plan holds a NUL character.', NEXT_STEP_REGENERATE));
  }
  return stream(fields);
}

const HOLDER_TYPE = /^(lvm|crypt|raid.*)$/;

function hasHolderDescendant(device) {
  return (Array.isArray(device.children) ? device.children : []).some(child => (
    (isRecord(child) && HOLDER_TYPE.test(String(child.type))) || (isRecord(child) && hasHolderDescendant(child))
  ));
}

// The read-only re-read of the disk against the plan (pre-check step 6a), and the LVM, dm-crypt, and md
// descendants of the disk in the collector's device tree (the device-mapper part of step 6b).
export function checkDisk(text, rawStorage) {
  const parsed = parsePlanText(text);
  if (parsed.plan === undefined) return failure('blocked', parsed.reasons[0]);
  const { facts } = normalizeStorage(rawStorage, 0);
  const disk = selectedDisk(parsed.plan, { layers: { detected: { storage: facts } } });
  const differences = diskDifferences(parsed.plan, disk, { ignoreMounts: true });
  if (differences.length > 0) return failure('invalidated', differences[0]);
  const raw = (Array.isArray(rawStorage?.blockdevices) ? rawStorage.blockdevices : []).find(device => device.path === disk.identity.path);
  if (raw !== undefined && hasHolderDescendant(raw)) {
    return failure('blocked', reason(
      'target_disk_in_use',
      'The confirmed disk has an LVM, dm-crypt, or RAID device on top of it.',
      'Release it manually (close the mapping or stop the array) or run mirroros-install again; the disk was not touched.',
    ));
  }
  return stream(['ok']);
}

function main(args) {
  const [mode] = args;
  const text = readFileSync(0, 'utf8');
  if (mode === 'verify') {
    process.stdout.write(verifyPlan(text, {
      digest: readOption(args, '--digest'),
      commit: readOption(args, '--commit'),
      dirty: readOption(args, '--dirty'),
    }));
  } else if (mode === 'check-disk') {
    let raw;
    try {
      raw = JSON.parse(readFileSync(readOption(args, '--storage'), 'utf8'));
    } catch (error) {
      process.stdout.write(failure('blocked', reason(
        'stage_failed',
        `The storage collector output cannot be read (${error.code ?? error.name}).`,
        'Rerun mirroros-install; the disk was not touched.',
      ), 'precheck'));
      return;
    }
    process.stdout.write(checkDisk(text, raw));
  } else {
    process.stderr.write('Usage: load-plan.mjs verify|check-disk ...\n');
    process.exitCode = 2;
  }
}

if (process.argv[1] !== undefined && import.meta.url === pathToFileURL(process.argv[1]).href) {
  try {
    main(process.argv.slice(2));
  } catch (error) {
    process.stderr.write(`The plan loader failed an internal contract check: ${error.message}\n`);
    process.exitCode = 6;
  }
}
