import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdirSync, mkdtempSync, readFileSync, rmSync, statSync, writeFileSync, chmodSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import {
  SELECTION_MARKER, applyRegionalMirrors, countryCodeForTimezone, sectionNameForCountry, selectRegion,
} from '../../../install/confirmation/regional-mirrors.mjs';

const ZONE_TAB = [
  '# tzdb timezone descriptions',
  'ES\t+4024-00341\tEurope/Madrid\tSpain (mainland)',
  'ES\t+2806-01524\tAtlantic/Canary\tCanary Islands',
  'GB\t+513030-0000731\tEurope/London',
  'AQ\t-7750+16636\tAntarctica/McMurdo',
  '',
].join('\n');
const ISO_TAB = ['# ISO 3166 alpha-2 country codes', 'ES\tSpain', 'GB\tBritain (UK)', 'AQ\tAntarctica', ''].join('\n');

// The shape of the live mirrorlist: pacman-mirrorlist after the releng hook uncommented the HTTPS servers.
const LIVE = [
  '##',
  '## Arch Linux repository mirrorlist',
  '## Generated on 2026-10-15',
  '##',
  '',
  '## Worldwide',
  'Server = https://fastly.example/$repo/os/$arch',
  'Server = https://rackspace.example/$repo/os/$arch',
  '',
  '## Albania',
  'Server = https://al.example/$repo/os/$arch',
  '',
  '## Spain',
  'Server = https://es-one.example/$repo/os/$arch',
  '#Server = http://es-plain.example/$repo/os/$arch',
  'Server = https://es-two.example/$repo/os/$arch',
  '',
  '## United Kingdom',
  'Server = https://uk.example/$repo/os/$arch',
  '',
].join('\n');

const activeServers = text => text.split('\n').filter(line => line.startsWith('Server'));

test('a time zone maps to its zone.tab country and section name', () => {
  assert.equal(countryCodeForTimezone(ZONE_TAB, 'Europe/Madrid'), 'ES');
  assert.equal(countryCodeForTimezone(ZONE_TAB, 'Atlantic/Canary'), 'ES');
  assert.equal(countryCodeForTimezone(ZONE_TAB, 'Etc/UTC'), null);
  assert.equal(sectionNameForCountry(ISO_TAB, 'ES'), 'Spain');
  assert.equal(sectionNameForCountry(ISO_TAB, 'GB'), 'United Kingdom');
  assert.equal(sectionNameForCountry(ISO_TAB, 'ZZ'), null);
});

test('the country comes first, Worldwide second, and every other server is commented out', () => {
  const result = selectRegion(LIVE, 'Spain');
  assert.equal(result.status, 'selected');
  assert.equal(result.servers, 2);
  assert.deepEqual(activeServers(result.text), [
    'Server = https://es-one.example/$repo/os/$arch',
    'Server = https://es-two.example/$repo/os/$arch',
    'Server = https://fastly.example/$repo/os/$arch',
    'Server = https://rackspace.example/$repo/os/$arch',
  ]);
  assert.ok(result.text.includes('#Server = http://es-plain.example/$repo/os/$arch'));
  assert.ok(result.text.includes('#Server = https://al.example/$repo/os/$arch'));
  assert.ok(result.text.includes('#Server = https://uk.example/$repo/os/$arch'));
  assert.ok(result.text.startsWith('##\n## Arch Linux repository mirrorlist\n## Generated on 2026-10-15\n##\n'));
  assert.ok(result.text.includes(SELECTION_MARKER));
  assert.equal(result.text.split('\n').filter(line => /Server\s*=/.test(line)).length, 7);
});

test('every doubt leaves the mirrorlist unchanged', () => {
  const selected = selectRegion(LIVE, 'Spain').text;
  const commentedSpain = LIVE.replace(/^Server = https:\/\/es-/gm, '#Server = https://es-');
  const bootMirror = '#\n# Arch Linux repository mirrorlist\n# Generated by archiso\n#\n\nServer = https://chosen.example/$repo/os/$arch\n';
  for (const [text, section] of [
    [LIVE, 'Antarctica'], [commentedSpain, 'Spain'], [bootMirror, 'Spain'], [selected, 'Spain'],
  ]) {
    assert.equal(selectRegion(text, section).status, 'unchanged');
  }
});

test('the live file is replaced in place with its mode, and left alone on a fallback', t => {
  const root = mkdtempSync(join(tmpdir(), 'regional-mirrors-'));
  t.after(() => rmSync(root, { recursive: true, force: true }));
  mkdirSync(join(root, 'etc/pacman.d'), { recursive: true });
  mkdirSync(join(root, 'usr/share/zoneinfo'), { recursive: true });
  writeFileSync(join(root, 'usr/share/zoneinfo/zone.tab'), ZONE_TAB);
  writeFileSync(join(root, 'usr/share/zoneinfo/iso3166.tab'), ISO_TAB);
  const mirrorlist = join(root, 'etc/pacman.d/mirrorlist');
  writeFileSync(mirrorlist, LIVE);
  chmodSync(mirrorlist, 0o644);

  assert.deepEqual(applyRegionalMirrors(root, 'Etc/UTC').status, 'unchanged');
  assert.equal(readFileSync(mirrorlist, 'utf8'), LIVE);

  assert.deepEqual(applyRegionalMirrors(root, 'Europe/Madrid'), { status: 'selected', section: 'Spain', servers: 2 });
  assert.equal(readFileSync(mirrorlist, 'utf8'), selectRegion(LIVE, 'Spain').text);
  assert.equal(statSync(mirrorlist).mode & 0o777, 0o644);

  assert.equal(applyRegionalMirrors(join(root, 'missing'), 'Europe/Madrid').status, 'unchanged');
});
